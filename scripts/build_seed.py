"""Build supabase/seed/*.sql from the game's content files.

Run from the repo root:  python3 -I scripts/build_seed.py
The story choices and question bank in the database must match src/content, so
regenerate and re-apply the seed whenever those files change.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase" / "seed"


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def jlit(o) -> str:
    return lit(json.dumps(o, ensure_ascii=False)) + "::jsonb"


def story_choices():
    src = (ROOT / "src/content/story.ts").read_text(encoding="utf-8")
    good = int(re.search(r"export const GOOD_XP = (\d+)", src).group(1))
    okay = int(re.search(r"export const OKAY_XP = (\d+)", src).group(1))
    rows = []
    for m in re.finditer(r"id: '(s\d)([a-z])',\s*trait: (null|'(\w+)'),\s*xp: (GOOD_XP|OKAY_XP)", src):
        scene, letter, _, trait, xp = m.groups()
        rows.append((scene + letter, scene, trait, good if xp == "GOOD_XP" else okay))
    scenes = {r[1] for r in rows}
    assert len(scenes) == 5 and len(rows) == 20, (len(scenes), len(rows))
    return rows


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = story_choices()
    sql = ["-- Generated by scripts/build_seed.py. Story choices from src/content/story.ts.",
           "insert into cs.story_choices (id, scene, trait, xp) values"]
    sql.append(",\n".join(
        f"  ({lit(i)}, {lit(s)}, {lit(t) if t else 'null'}, {xp})" for i, s, t, xp in rows))
    sql.append("on conflict (id) do update set scene = excluded.scene, trait = excluded.trait, xp = excluded.xp;\n")

    qs = json.loads((ROOT / "src/content/questions.json").read_text(encoding="utf-8"))
    sql.append("-- Question bank from src/content/questions.json.")
    sql.append("insert into cs.questions (id, band, subject, q, a, fix, correct) values")
    sql.append(",\n".join(
        f"  ({lit(q['id'])}, {lit(q['band'])}, {lit(q['subject'])}, {jlit(q['q'])}, {jlit(q['a'])}, {jlit(q['fix'])}, {str(q['correct']).lower()})"
        for q in qs))
    sql.append("on conflict (id) do update set band = excluded.band, subject = excluded.subject, q = excluded.q,\n"
               "  a = excluded.a, fix = excluded.fix, correct = excluded.correct, active = true;")
    ids = ", ".join(lit(q["id"]) for q in qs)
    sql.append(f"update cs.questions set active = false where id not in ({ids});\n")

    sql.append("-- The first event.")
    sql.append("""insert into cs.events (slug, name, starts_on, ends_on, offer_code, offer_valid_until, whatsapp, ref_prefix)
values ('peskon26', 'PESKON UPSI 2026', '2026-11-25', '2026-12-02', 'PESKON UPSI 2026', '2026-12-02', '601175234588', 'PK')
on conflict (slug) do update set name = excluded.name, starts_on = excluded.starts_on, ends_on = excluded.ends_on,
  offer_code = excluded.offer_code, offer_valid_until = excluded.offer_valid_until, whatsapp = excluded.whatsapp;
""")
    (OUT / "content.sql").write_text("\n".join(sql), encoding="utf-8")
    print(f"wrote {OUT / 'content.sql'}: {len(rows)} story choices, {len(qs)} questions")


if __name__ == "__main__":
    main()
